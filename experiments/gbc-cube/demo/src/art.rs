/// RGB → BGR555, the CGB's palette RAM format.
pub const fn bgr(r: u8, g: u8, b: u8) -> u16 {
    (r as u16 >> 3) | ((g as u16 >> 3) << 5) | ((b as u16 >> 3) << 10)
}


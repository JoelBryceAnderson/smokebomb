/// A round, cheerful monster for the battle screen, 6×6 tiles, drawn with
/// BG palette 4 (colour 0 is the battle background).
pub fn blob(x: usize, y: usize) -> u8 {
    // A disc with a darker rim, eyes and a smile, in 48×48 px.
    let (cx, cy) = (23.5f32, 26.0f32);
    let (dx, dy) = (x as f32 - cx, (y as f32 - cy) * 1.15);
    let r = (dx * dx + dy * dy).sqrt();
    if r > 22.0 {
        return 0;
    }
    let eye = |ex: f32| ((x as f32 - ex).powi(2) + (y as f32 - 20.0).powi(2)).sqrt() < 3.2;
    if eye(15.0) || eye(32.0) {
        return 3;
    }
    let smile =
        (y as f32 - 30.0 - ((x as f32 - 23.5) / 8.0).powi(2)).abs() < 1.2 && (x as f32 - 23.5).abs() < 9.0;
    if smile || r > 20.0 {
        return 3;
    }
    if dy < -10.0 && dx < -4.0 && r < 17.0 {
        return 1; // shine
    }
    2
}
